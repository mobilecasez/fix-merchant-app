// ── Severity helpers ──────────────────────────────────────────────────────────

function severityColor(s: string) {
  if (s === "High") return "#d72c0d";
  if (s === "Medium") return "#b98900";
  return "#637381";
}

function severityBg(s: string) {
  if (s === "High") return "#fef2f2";
  if (s === "Medium") return "#fffbeb";
  return "#f0f9ff";
}

// ── Excel builder ─────────────────────────────────────────────────────────────

function buildExcel(scan: any, storeName: string): Buffer {
  const result = scan.result as any;
  const summary = result?.scan_summary || {};
  const wb = XLSX.utils.book_new();

  // Summary sheet
  const summaryData = [
    ["Store GMC Compliance Report — ShopFlix AI"],
    [],
    ["Store Name", storeName],
    ["Store URL", summary.store_url || ""],
    ["Overall Risk", summary.overall_risk || ""],
    ["Pages Scanned", summary.pages_scanned ?? ""],
    ["Missing Required Pages", summary.pages_missing ?? ""],
    ["Broken Links Found", summary.broken_links_found ?? ""],
    ["Scan Date", new Date(scan.updatedAt).toLocaleString()],
    ["Generated By", "ShopFlix AI (shopflixai.com)"],
  ];
  const summarySheet = XLSX.utils.aoa_to_sheet(summaryData);
  summarySheet["!cols"] = [{ wch: 28 }, { wch: 60 }];
  XLSX.utils.book_append_sheet(wb, summarySheet, "Summary");

  const addSheet = (sheetName: string, issues: any[]) => {
    if (!issues?.length) return;
    const headers = ["#", "Severity", "Issue Description", "Suggested Fix", "Fix Steps", "Auto Fixable", "Credit Cost"];
    const rows = issues.map((issue: any, i: number) => [
      i + 1,
      issue.severity || "",
      issue.issue_description || issue.label || issue.url || "",
      issue.suggested_fix || "",
      Array.isArray(issue.detailed_fix_steps) ? issue.detailed_fix_steps.join("\n") : "",
      issue.auto_fixable ? "Yes" : "No",
      issue.credit_cost ?? "",
    ]);
    const ws = XLSX.utils.aoa_to_sheet([headers, ...rows]);
    ws["!cols"] = [{ wch: 4 }, { wch: 10 }, { wch: 50 }, { wch: 40 }, { wch: 60 }, { wch: 12 }, { wch: 10 }];
    XLSX.utils.book_append_sheet(wb, ws, sheetName);
  };

  if (result?.missing_pages?.length) {
    const headers = ["#", "Page", "URL", "Severity", "Suggested Fix", "Fix Steps"];
    const rows = result.missing_pages.map((p: any, i: number) => [
      i + 1, p.label || "", p.url || "", p.severity || "High",
      p.suggested_fix || "",
      Array.isArray(p.detailed_fix_steps) ? p.detailed_fix_steps.join("\n") : "",
    ]);
    const ws = XLSX.utils.aoa_to_sheet([headers, ...rows]);
    ws["!cols"] = [{ wch: 4 }, { wch: 22 }, { wch: 40 }, { wch: 10 }, { wch: 40 }, { wch: 60 }];
    XLSX.utils.book_append_sheet(wb, ws, "Missing Pages");
  }

  if (result?.broken_links?.length) {
    const headers = ["#", "URL", "Severity", "Suggested Fix"];
    const rows = result.broken_links.map((l: any, i: number) => [i + 1, l.url || "", "High", l.suggested_fix || ""]);
    const ws = XLSX.utils.aoa_to_sheet([headers, ...rows]);
    ws["!cols"] = [{ wch: 4 }, { wch: 50 }, { wch: 10 }, { wch: 50 }];
    XLSX.utils.book_append_sheet(wb, ws, "Broken Links");
  }

  addSheet("GMC Compliance", result?.merchant_center_compliance);
  addSheet("Customer Trust & Policy", result?.customer_trust_and_policy);
  addSheet("Site Structure & SEO", result?.site_structure_and_seo);

  return XLSX.write(wb, { type: "buffer", bookType: "xlsx" }) as Buffer;
}

