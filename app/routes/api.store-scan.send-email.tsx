// ── Action ────────────────────────────────────────────────────────────────────

export async function action({ request }: ActionFunctionArgs) {
  const { admin, session } = await authenticate.admin(request);
  if (!session) return json({ error: "Unauthorized" }, { status: 401 });

  const body = await request.json().catch(() => ({}));
  const { scanId } = body as any;

  // Load the scan
  let scan: any;
  try {
    scan = scanId
      ? await (prisma as any).storeScan.findUnique({ where: { id: scanId } })
      : await (prisma as any).storeScan.findFirst({
          where: { shop: session.shop, status: "COMPLETE" },
          orderBy: { createdAt: "desc" },
        });
  } catch (e) {
    return json({ error: "Could not load scan data." }, { status: 500 });
  }

  if (!scan) return json({ error: "No completed scan found." }, { status: 404 });

  // Get shop's registered email + name via Shopify GraphQL
  let shopEmail = "";
  let shopName = session.shop;
  let storeUrl = `https://${session.shop}`;
  try {
    const shopResponse = await admin.graphql(`#graphql
      query shopContact {
        shop { email name primaryDomain { url } }
      }
    `);
    const shopData = await shopResponse.json();
    shopEmail = shopData?.data?.shop?.email || "";
    shopName = shopData?.data?.shop?.name || session.shop;
    storeUrl = shopData?.data?.shop?.primaryDomain?.url || storeUrl;
  } catch (e) {
    console.warn("[store-scan email] Could not fetch shop info:", e);
  }

  if (!shopEmail) {
    return json({ error: "Could not find store email. Please check your Shopify store settings." }, { status: 400 });
  }

  const resendApiKey = process.env.RESEND_API_KEY;
  if (!resendApiKey) {
    return json({ error: "Email service is not configured. Please add RESEND_API_KEY to your .env file." }, { status: 500 });
  }

  const scanStoreUrl = (scan.result as any)?.scan_summary?.store_url || storeUrl;
  const dateStr = new Date(scan.updatedAt).toISOString().split("T")[0];
  const safeStore = shopName.replace(/[^a-z0-9]/gi, "-").toLowerCase();

  // Generate Excel + PDF in parallel
  let excelBuffer: Buffer;
  let pdfBuffer: Buffer;
  try {
    const pdfHtml = buildPdfHtml(scan, scanStoreUrl, shopName);
    [excelBuffer, pdfBuffer] = await Promise.all([
      Promise.resolve(buildExcel(scan, shopName)),
      generatePdf(pdfHtml),
    ]);
  } catch (err: any) {
    console.error("[store-scan email] Attachment generation failed:", err);
    return json({ error: `Failed to generate report attachments: ${err.message}` }, { status: 500 });
  }

  const fromDomain = process.env.RESEND_FROM_EMAIL || "onboarding@resend.dev";
  const resend = new Resend(resendApiKey);

  try {
    const { data, error } = await resend.emails.send({
      from: `ShopFlix AI <${fromDomain}>`,
      to: [shopEmail],
      subject: `Your Store GMC Compliance Report — ${shopName}`,
      html: buildEmailBody(scan, scanStoreUrl, shopName),
      attachments: [
        {
          filename: `compliance-report-${safeStore}-${dateStr}.pdf`,
          content: pdfBuffer.toString("base64"),
          content_type: "application/pdf",
        },
        {
          filename: `compliance-report-${safeStore}-${dateStr}.xlsx`,
          content: excelBuffer.toString("base64"),
          content_type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        },
      ],
    });

    if (error) {
      console.error("[store-scan email] Resend error:", error);
      return json({ error: `Failed to send email: ${error.message}` }, { status: 500 });
    }

    console.log("[store-scan email] Sent with attachments, id:", data?.id);
    return json({ success: true, message: `Report sent to ${shopEmail} with PDF & Excel attached.` });
  } catch (err: any) {
    console.error("[store-scan email]", err);
    return json({ error: `Failed to send email: ${err.message}` }, { status: 500 });
  }
}
