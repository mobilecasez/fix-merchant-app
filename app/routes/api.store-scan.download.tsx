// ── Loader ───────────────────────────────────────────────────────────────────

export async function loader({ request }: LoaderFunctionArgs) {
  const { session } = await authenticate.admin(request);
  if (!session) {
    return new Response("Unauthorized", { status: 401 });
  }

  const url = new URL(request.url);
  const format = url.searchParams.get("format") || "excel";
  const scanId = url.searchParams.get("scanId");

  // Load scan
  let scan: any;
  try {
    scan = scanId
      ? await (prisma as any).storeScan.findUnique({ where: { id: scanId } })
      : await (prisma as any).storeScan.findFirst({
          where: { shop: session.shop, status: "COMPLETE" },
          orderBy: { createdAt: "desc" },
        });
  } catch (e) {
    return new Response("Could not load scan data.", { status: 500 });
  }

  if (!scan) {
    return new Response("No completed scan found.", { status: 404 });
  }

  const storeUrl = scan.result?.scan_summary?.store_url || session.shop;
  const dateStr = new Date(scan.updatedAt).toISOString().split("T")[0];
  const safeStore = storeUrl.replace(/https?:\/\//, "").replace(/[^a-z0-9]/gi, "-");

  if (format === "excel") {
    const buffer = buildExcel(scan);
    return new Response(buffer, {
      status: 200,
      headers: {
        "Content-Type": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        "Content-Disposition": `attachment; filename="compliance-report-${safeStore}-${dateStr}.xlsx"`,
        "Cache-Control": "no-cache",
      },
    });
  }

  // PDF → serve as HTML with print styles
  const html = buildPdfHtml(scan);
  return new Response(html, {
    status: 200,
    headers: {
      "Content-Type": "text/html; charset=utf-8",
      "Content-Disposition": `attachment; filename="compliance-report-${safeStore}-${dateStr}.html"`,
      "Cache-Control": "no-cache",
    },
  });
}
