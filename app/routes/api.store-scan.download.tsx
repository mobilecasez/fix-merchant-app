import { type LoaderFunctionArgs } from "@remix-run/node";
import { authenticate } from "../shopify.server";
import prisma from "../db.server";
import * as XLSX from "xlsx";

function severityColor(s: string) {
  if (s === "High") return "#d72c0d";
  if (s === "Medium") return "#b98900";
  return "#637381";
}

function severityBg(s: string) {
  if (s === "High") return "#fef2f2";
  if (s === "Medium") return "#fffbeb";
  return "#f0f9ff";
}

// ── Excel builder ────────────────────────────────────────────────────────────

function buildExcel(scan: any): Buffer {
  const result = scan.result as any;
  const summary = result?.scan_summary || {};
  const wb = XLSX.utils.book_new();

  // Summary sheet
  const summaryData = [
    ["Store GMC Compliance Report"],
    [],
    ["Store URL", summary.store_url || ""],
    ["Overall Risk", summary.overall_risk || ""],
    ["Pages Scanned", summary.pages_scanned ?? ""],
    ["Missing Required Pages", summary.pages_missing ?? ""],
    ["Broken Links Found", summary.broken_links_found ?? ""],
    ["Scan Date", new Date(scan.updatedAt).toLocaleString()],
    ["Generated By", "ShopFlix AI"],
  ];
  const summarySheet = XLSX.utils.aoa_to_sheet(summaryData);
  summarySheet["!cols"] = [{ wch: 28 }, { wch: 50 }];
  XLSX.utils.book_append_sheet(wb, summarySheet, "Summary");

  // Helper to build an issue sheet
  const addIssueSheet = (sheetName: string, issues: any[], isMissingPages = false, isBrokenLinks = false) => {
    const headers = ["#", "Severity", "Issue Description", "Suggested Fix", "Fix Steps", "Auto Fixable", "Auto Fix Type", "Credit Cost"];
    if (isMissingPages) {
      headers.splice(2, 0, "Page Label", "URL");
    }
    if (isBrokenLinks) {
      headers.splice(2, 0, "URL");
    }

    const rows: any[][] = [headers];

    (issues || []).forEach((issue: any, i: number) => {
      const steps = Array.isArray(issue.detailed_fix_steps)
        ? issue.detailed_fix_steps.join("\n")
        : (issue.detailed_fix_steps || "");

      if (isMissingPages) {
        rows.push([
          i + 1,
          issue.severity || "",
          issue.label || "",
          issue.url || "",
          issue.suggested_fix || "",
          steps,
          issue.auto_fixable ? "Yes" : "No",
          issue.auto_fix_type || "",
          issue.credit_cost ?? "",
        ]);
      } else if (isBrokenLinks) {
        rows.push([
          i + 1,
          issue.severity || "High",
          issue.url || "",
          issue.suggested_fix || "",
          steps,
          issue.auto_fixable ? "Yes" : "No",
          issue.auto_fix_type || "",
          issue.credit_cost ?? "",
        ]);
      } else {
        rows.push([
          i + 1,
          issue.severity || "",
          issue.issue_description || "",
          issue.suggested_fix || "",
          steps,
          issue.auto_fixable ? "Yes" : "No",
          issue.auto_fix_type || "",
          issue.credit_cost ?? "",
        ]);
      }
    });

    const sheet = XLSX.utils.aoa_to_sheet(rows);
    sheet["!cols"] = [
      { wch: 4 }, { wch: 10 }, { wch: 50 }, { wch: 50 }, { wch: 60 }, { wch: 14 }, { wch: 18 }, { wch: 12 },
    ];
    XLSX.utils.book_append_sheet(wb, sheet, sheetName);
  };

  addIssueSheet("GMC Compliance", result?.merchant_center_compliance || []);
  addIssueSheet("Customer Trust & Policy", result?.customer_trust_and_policy || []);
  addIssueSheet("Site Structure & SEO", result?.site_structure_and_seo || []);
  addIssueSheet("Missing Pages", result?.missing_pages || [], true);
  addIssueSheet("Broken Links", result?.broken_links || [], false, true);

  return XLSX.write(wb, { type: "buffer", bookType: "xlsx" }) as Buffer;
}

// ── PDF (HTML) builder ───────────────────────────────────────────────────────

function badge(severity: string) {
  return `<span style="display:inline-block;padding:2px 8px;border-radius:4px;font-size:11px;font-weight:700;background:${severityBg(severity)};color:${severityColor(severity)};border:1px solid ${severityColor(severity)}20">${severity}</span>`;
}

function issuesHtml(issues: any[], isMissingPages = false, isBrokenLinks = false): string {
  if (!issues?.length) {
    return `<p style="color:#12a04a;margin:0;font-size:14px">✓ No issues found in this category.</p>`;
  }
  return issues.map((issue: any, i: number) => {
    const sev = issue.severity || (isBrokenLinks ? "High" : "Medium");
    const desc = isMissingPages
      ? `<strong>${issue.label}</strong> — <a href="${issue.url}" style="color:#006ECB">${issue.url}</a>`
      : isBrokenLinks
      ? `<a href="${issue.url}" style="color:#006ECB">${issue.url}</a>`
      : (issue.issue_description || "");

    const steps = Array.isArray(issue.detailed_fix_steps) && issue.detailed_fix_steps.length
      ? `<ol style="margin:8px 0 0 0;padding-left:20px;color:#444;font-size:13px;line-height:1.7">${issue.detailed_fix_steps.map((s: string) => `<li>${s}</li>`).join("")}</ol>`
      : "";

    const autoFixBadge = issue.auto_fixable
      ? `<span style="display:inline-block;margin-left:8px;padding:2px 8px;border-radius:4px;font-size:11px;font-weight:600;background:#eff6ff;color:#1d4ed8;border:1px solid #bfdbfe">⚡ Auto-fixable (${issue.credit_cost ?? "?"} credits)</span>`
      : "";

    return `
      <div style="border-left:3px solid ${severityColor(sev)};padding-left:14px;margin-bottom:18px;page-break-inside:avoid">
        <div style="display:flex;align-items:flex-start;gap:8px;flex-wrap:wrap;margin-bottom:6px">
          ${badge(sev)}
          ${autoFixBadge}
          <span style="font-size:14px;color:#212121;font-weight:600;flex:1">${desc}</span>
        </div>
        ${issue.suggested_fix ? `<p style="margin:0 0 6px 0;font-size:13px;color:#555;line-height:1.5">💡 ${issue.suggested_fix}</p>` : ""}
        ${steps}
      </div>
    `;
  }).join("");
}

function sectionHtml(title: string, issues: any[], isMissingPages = false, isBrokenLinks = false): string {
  if (!issues?.length) return "";
  return `
    <div style="background:#fff;border-radius:8px;border:1px solid #e5e7eb;padding:24px;margin-bottom:20px;page-break-inside:avoid">
      <h3 style="margin:0 0 16px 0;font-size:17px;font-weight:700;color:#212121;border-bottom:1px solid #f0f0f0;padding-bottom:10px">${title}</h3>
      ${issuesHtml(issues, isMissingPages, isBrokenLinks)}
    </div>
  `;
}

